// ---- 蚀变 (游戏设计 四「词怎么分层、蚀变和挑战怪」) ------------------------------------------------------------
// The second-to-last segment of a stage goes back to old maps: same scenes and ids, a second word group per chosen
// scene (the advanced layer of its life situation), monsters at the segment's level, its own gear tiers. Groups and
// host scenes come from the lexicon (《6000词进场景-第1版》: 蚀变① 59 groups on regions 1–3, 蚀变② on regions 1–7).

export interface ErodeScene {
  scene: string;
  /** The field (word pool) the old scene belongs to. */
  zone: ZoneId;
}

export interface ErodeDef {
  seg: 8 | 11;
  /** Name shown in banners and the 图鉴. */
  zh: string;
  stage: 'A2' | 'B1';
  /** Opens once this boss has fallen (the last new region before it). */
  after: number;
  /** The old region whose boss door the segment's boss stands behind, with the door's lines. */
  bossRegion: 1 | 2 | 3 | 4 | 5 | 6 | 7;
  doorZh: string;
  doorAct: string;
  /** Said when it opens. */
  open: string[];
  /** 蚀变① has its own ramp (游戏设计 十三); 蚀变② darkens each old map's own (src/game/palette.ts). */
  palette?: [string, string, string, string, string];
  scenes: ErodeScene[];
}

/** Field zone of every field scene (from the lexicon). */
const ZONE_OF_SCENE = new Map(LEX_SCENES.map(([id, region, field]) => [id, LEX_FIELDS[region][field][0] as ZoneId]));
/** The old scenes a 蚀变 segment hangs its groups on (picked by scripts/build_lexicon.py: the scene with most of the
 *  group's ladder base words, else one of the same situation, else a free one; each scene carries one layer). */
function erodeScenes(seg: 8 | 11): ErodeScene[] {
  return LEX_ERODED.filter(([, g]) => g === seg).map(([scene]) => ({ scene, zone: ZONE_OF_SCENE.get(scene)! }));
}

