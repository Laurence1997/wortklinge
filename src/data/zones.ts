export const ERODE_DEF: Partial<Record<number, ErodeDef>> = Object.fromEntries(ERODE_DEFS.map((e) => [e.seg, e]));

/** The segment after `seg` that has a map (7 → 9, 10 → 12, 14 → 16, 18 → 20), or null after 20. */
export function nextMapRegion(seg: number): number | null {
  for (let r = seg + 1; r <= 20; r++) if (REGION_DEF[r]) return r;
  return null;
}

/** The map region before `r` (9 → 7, 12 → 10, 4 → 3). */
export function prevMapRegion(r: number): number {
  for (let p = r - 1; p >= 4; p--) if (REGION_DEF[p]) return p;
  return 3;
}

/** Level band of a region: 4 → 31–40 … 20 → 191–200. */
export function regionLevels(region: number): [number, number] {
  return [(region - 1) * 10 + 1, region * 10];
}

/** Field scene ids of a region, per field (route order), from the lexicon. */
export function fieldScenes(region: number): string[][] {
  const out: string[][] = (LEX_FIELDS[region] ?? []).map(() => []);
  for (const [id, r, f] of LEX_SCENES) if (r === region) out[f].push(id);
  return out;
}

/** Level band of a field inside its region: its share of the region's scenes (words climb scene by scene). */
export function fieldLevels(region: number, field: number): [number, number] {
  const [lo, hi] = regionLevels(region);
  const counts = fieldScenes(region).map((x) => x.length);
  const n = counts.reduce((a, b) => a + b, 0) || 1;
  const before = counts.slice(0, field).reduce((a, b) => a + b, 0);
  return [Math.round(lo + ((hi - lo) * before) / n), Math.round(lo + ((hi - lo) * (before + (counts[field] ?? 0))) / n)];
}

