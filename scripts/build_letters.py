#!/usr/bin/env python3
"""失语者的遗书 (游戏设计 剧情, 1.0): data/wortschatz/briefe-1.0.tsv → src/data/letters.ts. Run again after the TSV changes."""
import csv, json, os


def _fold(a, n):
    """Merge a short greeting (first) or signature (last) paragraph into its neighbour until a has n paragraphs."""
    a = list(a)
    while len(a) > n:
        if len(a[0]) <= len(a[-1]):
            a[:2] = [a[0] + ' ' + a[1]]
        else:
            a[-2:] = [a[-2] + ' ' + a[-1]]
    return a


def align(de, zh):
    """German and Chinese show side by side paragraph by paragraph; a greeting or signature split on one side only is folded in."""
    n = min(len(de), len(zh))
    return _fold(de, n), _fold(zh, n)


ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = list(csv.DictReader(open(os.path.join(ROOT, 'data/wortschatz/briefe-1.0.tsv'), encoding='utf-8'), delimiter='\t'))
out = []
for r in rows:
    de = [p.strip() for p in r['例句'].split('｜') if p.strip()]
    zh = [p.strip() for p in r['例句中文'].split('｜') if p.strip()]
    de, zh = align(de, zh)
    out.append({
        'id': r['id'], 'region': int(r['区']), 'n': int(r['序号']), 'from': r['写信人'].strip(), 'main': r['主线'].strip() or None,
        'title': r['标题'].strip(), 'de': de, 'zh': zh, 'words': [w.strip() for w in r['本区词'].split(',') if w.strip()],
        'grammar': r['语法'].strip(), 'clue': r['线索'].strip(), 'src': r['例句出处'].strip(),
    })
with open(os.path.join(ROOT, 'src/data/letters.ts'), 'w', encoding='utf-8') as f:
    f.write('// 失语者的遗书 · generated by scripts/build_letters.py from data/wortschatz/briefe-1.0.tsv — do not edit by hand.\n')
    f.write("import type { Letter } from '../core/letters';\n\n")
    f.write('export const LETTERS: Letter[] = ' + json.dumps(out, ensure_ascii=False, indent=0).replace('\n', '') + ';\n')
print(len(out), 'letters')
