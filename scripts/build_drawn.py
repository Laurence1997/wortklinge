#!/usr/bin/env python3
"""Code-drawn monster looks (专属造型, Lucas 2026-11-25): data/monster-art/sprites.txt → src/data/drawnArt.ts.

Each block is '= <原形>' and 16 rows of 16 palette characters. The word id comes from src/data/lexicon.ts, so run
build_lexicon.py first when the word list changed."""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAL = {'o': '#3f2631', 'r': '#c34b35', 'R': '#aa2c23', 'p': '#f28462', 'g': '#4e974c', 'G': '#84c669', 'l': '#c6e58d',
       'y': '#fdbe53', 'Y': '#e38628', 'w': '#ffd896', 'n': '#cf8254', 'N': '#eaa56c', 'm': '#fec99c', 'b': '#763b36',
       'B': '#bd6c4a', 's': '#52607c', 'S': '#8b9bb4', 'c': '#c0cbdc', 'W': '#ebeff8', 'h': '#ffffff', 'u': '#79a7e8',
       'U': '#99d8f8', 'v': '#9b4ca3', 'V': '#d176d0', 'k': '#262b44'}

def main():
    lex = (ROOT / 'src/data/lexicon.ts').read_text(encoding='utf-8')
    rows = json.loads(re.search(r'export const LEX_ROWS: string = (".*?");\n', lex, re.S).group(1)).split('\n')
    ids = {}
    for r in rows:
        f = r.split('\t')
        ids.setdefault(f[1], f[0])
    blocks, cur, name = {}, [], None
    for line in (ROOT / 'data/monster-art/sprites.txt').read_text(encoding='utf-8').split('\n'):
        if line.startswith('#'):
            continue
        if line.startswith('= '):
            name, cur = line[2:].strip(), []
            continue
        if name and line.strip():
            cur.append(line.rstrip('\n'))
            if len(cur) == 16:
                blocks[name] = cur
                name = None
    out, bad = {}, []
    for de, rs in blocks.items():
        if any(len(r) != 16 for r in rs) or set(''.join(rs)) - set(PAL) - {'.'}:
            bad.append(de)
            continue
        if de not in ids:
            bad.append(de + ' (not in the word list)')
            continue
        out[ids[de]] = '/'.join(rs)
    if bad:
        print('skipped:', ', '.join(bad), file=sys.stderr)
    ts = ['// GENERATED by scripts/build_drawn.py from data/monster-art/sprites.txt. Do not edit by hand.',
          '/* eslint-disable */',
          '/** Palette characters → colours (Kenney Tiny colours). */',
          'export const DRAWN_PAL: Record<string, string> = ' + json.dumps(PAL) + ';',
          '/** Code-drawn monster looks by word id: 16 rows of 16 palette characters, joined by "/". */',
          'export const DRAWN: Record<string, string> = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';', '']
    (ROOT / 'src/data/drawnArt.ts').write_text('\n'.join(ts), encoding='utf-8')
    print(f'{len(out)} drawn looks')

if __name__ == '__main__':
    main()
