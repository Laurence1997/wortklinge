#!/usr/bin/env python3
"""Recipes → sprites (专属造型 batch 2, 2026-11-26).

data/monster-art/recipes.txt holds one line per word: '<原形>: <family> key=value …'. Families: person, group, building,
flag, doc, card, bottle, room, plus 'raw' blocks in data/monster-art/sprites-2.txt (hand-drawn without outline; this
script adds the outline). Output: data/monster-art/sprites-gen.txt in the same block format as sprites.txt, which
build_drawn.py reads after sprites.txt (a hand-drawn block in sprites.txt always wins)."""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from artlib import grid, text, outline, center, eyes  # noqa: E402
import art_people  # noqa: E402
import art_things  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / 'data/monster-art'


def parse_spec(words):
    spec = {}
    for w in words:
        if '=' in w:
            k, v = w.split('=', 1)
            spec[k] = v
        else:
            spec[w] = '1'
    return spec


def render(family, rest):
    if family == 'person':
        return art_people.person(parse_spec(rest.split()))
    if family == 'group':
        parts = re.findall(r'\(([^)]*)\)', rest)
        return outline(art_people.group([parse_spec(p.split()) for p in parts]))
    fn = getattr(art_things, family, None)
    if fn is None:
        raise ValueError(f'unknown family {family}')
    return fn(parse_spec(rest.split()))


def raw_blocks():
    """Hand-drawn fill-only blocks in sprites-2.txt: a header '= Word' (options after '|': 'eyes x,y[ gap]',
    'noline', 'top') and up to 16 rows, ended by an empty line. Rows may be short; the drawing is centred and set on
    row 14 unless 'top' is given, and gets the outline."""
    out = {}
    p = ART / 'sprites-2.txt'
    if not p.exists():
        return out

    def finish(name, opts, cur):
        g = grid(cur)
        for o in opts:
            if o.startswith('eyes'):
                parts = o.split()
                x, y = map(int, parts[1].split(','))
                eyes(g, x, y, int(parts[2]) if len(parts) > 2 else 4)
        if 'top' not in opts:
            g = center(g)
        if 'noline' not in opts:
            outline(g)
        out[name] = g

    name, opts, cur = None, [], []
    for line in p.read_text(encoding='utf-8').split('\n') + ['']:
        if line.startswith('#'):
            continue
        if line.startswith('= '):
            head = line[2:].split('|')
            name, opts, cur = head[0].strip(), [o.strip() for o in head[1:]], []
            continue
        if name is None:
            continue
        if not line.strip():
            if cur:
                finish(name, opts, cur)
            name = None
            continue
        cur.append(line.rstrip())
    return out


def main():
    blocks = {}
    bad = []
    for n, line in enumerate((ART / 'recipes.txt').read_text(encoding='utf-8').split('\n'), 1):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        word, _, body = line.partition(':')
        body = body.strip()
        family, _, rest = body.partition(' ')
        try:
            blocks[word.strip()] = render(family, rest)
        except Exception as e:  # keep going, report at the end
            bad.append(f'{n} {word}: {e!r}')
    blocks.update(raw_blocks())
    lines = ['# GENERATED by scripts/gen_sprites.py from recipes.txt and sprites-2.txt. Do not edit by hand.', '']
    for w, g in blocks.items():
        lines.append(f'= {w}')
        lines += text(g)
        lines.append('')
    (ART / 'sprites-gen.txt').write_text('\n'.join(lines), encoding='utf-8')
    if bad:
        print('errors:\n  ' + '\n  '.join(bad), file=sys.stderr)
    print(f'{len(blocks)} generated looks')


if __name__ == '__main__':
    main()
