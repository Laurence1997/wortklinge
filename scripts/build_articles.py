#!/usr/bin/env python3
"""文章群怪 (游戏设计 四「121–200 级」): data/wortschatz/artikel-b2*.tsv → src/data/articlesB2-gen.ts. Run again after the TSVs change."""
import csv, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = []
for name in ('artikel-b2.tsv', 'artikel-b2-original.tsv', 'artikel-c1.tsv'):
    path = os.path.join(ROOT, 'data/wortschatz', name)
    if not os.path.exists(path):
        continue
    for r in sorted(csv.DictReader(open(path, encoding='utf-8'), delimiter='\t'), key=lambda r: r['id']):
        try:
            qs = json.loads(r['题目'] or '[]')
            gloss = json.loads(r['注释'] or '[]')
        except json.JSONDecodeError as e:
            print('skip', r['id'], e)
            continue
        de = [p.strip() for p in r['例句'].split('｜') if p.strip()]
        zh = [p.strip() for p in r['例句中文'].split('｜') if p.strip()]
        if not de or not qs:
            print('skip', r['id'], 'no text or questions')
            continue
        out.append({
            'id': r['id'], 'seg': int(r['段']), 'title': r['标题'].strip(), 'de': de, 'zh': zh,
            'lemmas': [w.strip() for w in r['新词'].split(',') if w.strip()],
            'gloss': [{'w': g.get('w', ''), 'de': g.get('de', ''), 'zh': g.get('zh', '')} for g in gloss],
            'qs': [{'q': q['q'], 'qZh': q.get('qZh', ''), 'answer': q['answer'], 'wrong': q['wrong'][:2]} for q in qs if q.get('answer') and len(q.get('wrong', [])) >= 2],
            'src': r['来源'].strip(), 'url': r['网址'].strip(), 'lic': r['许可证'].strip(),
            'original': r['id'].startswith('b2o-') or r['来源'].strip().startswith('原创'),
        })
# Two chunks: B2 (13–16, needed from 115) and C1 (17–20, needed from 155).
for fname, part in (('articlesB2-gen.ts', [a for a in out if a['seg'] < 17]), ('articlesC1-gen.ts', [a for a in out if a['seg'] >= 17])):
    with open(os.path.join(ROOT, 'src/data', fname), 'w', encoding='utf-8') as f:
        f.write('// 文章怪 · GENERATED by scripts/build_articles.py from data/wortschatz/artikel-*.tsv. Do not edit by hand.\n/* eslint-disable */\n')
        f.write("import type { ArticleB2 } from './articlesB2';\n\n")
        f.write('export const ARTICLE_ROWS: ArticleB2[] = ' + json.dumps(part, ensure_ascii=False) + ';\n')
print(len(out), 'articles')
