#!/usr/bin/env python3
"""1.0 extras: data/wortschatz/b2-aushaenge.tsv → src/data/grammar/noticesB2-gen.ts (B2 告示怪 / 信件怪, by region). A missing file gives an empty list. Run again after the TSVs change."""
import csv, json, os, random, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = os.path.join(ROOT, 'data/wortschatz')

notices = []
p = os.path.join(W, 'b2-aushaenge.tsv')
if os.path.exists(p):
    for r in csv.DictReader(open(p, encoding='utf-8'), delimiter='\t'):
        try:
            qs = json.loads(r['题目'] or '[]')
        except json.JSONDecodeError as e:
            print('skip', r['id'], e); continue
        kind = r['类型'].strip()
        text = '\n'.join(x.strip() for x in r['正文'].split('｜') if x.strip())
        qs = [q for q in qs if q.get('answer') and len(q.get('wrong', [])) >= 2]
        if kind not in ('notice', 'letter') or not text or not qs:
            print('skip', r['id'], 'kind/text/questions'); continue
        rnd = random.Random(r['id'])
        out_qs = []
        for q in qs:
            opts = [q['answer'], *q['wrong'][:2]]
            rnd.shuffle(opts)
            out_qs.append({'q': q['q'], 'qZh': q.get('qZh', ''), 'options': opts, 'answer': q['answer']})
        notices.append({'id': 'b2n-' + r['id'], 'zone': '', 'region': int(r['区']), 'kind': kind, 'title': r['标题'].strip(), 'text': text, 'qs': out_qs})
with open(os.path.join(ROOT, 'src/data/grammar/noticesB2-gen.ts'), 'w', encoding='utf-8') as f:
    f.write('// B2 告示怪 / 信件怪 · GENERATED by scripts/build_b2extras.py from data/wortschatz/b2-aushaenge.tsv. Do not edit by hand.\n/* eslint-disable */\n')
    f.write("import type { Notice } from './notices';\n\n")
    f.write('export const NOTICES_B2: Notice[] = ' + json.dumps(notices, ensure_ascii=False) + ';\n')

print(len(notices), 'B2 notices')
