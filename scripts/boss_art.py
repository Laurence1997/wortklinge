"""Boss figures (方案 B, Lucas 2026-11-26): one 32×32 pixel figure per boss, drawn as text in
data/boss-art/bosses.txt. A block starts with `# <key> [mirror]`; mirrored blocks give the left 16 columns and the right
half is the mirror image. Palette characters below; '.' is transparent. Every shape gets a 1-px near-black outline.

  python3 scripts/boss_art.py            → src/data/bossArt.ts
  python3 scripts/boss_art.py preview    → contact sheet PNG (path as 2nd arg)"""
import sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'data/boss-art/bosses.txt'
OUT = ROOT / 'src/data/bossArt.ts'
PAL = {
    'k': '#140405', 'b': '#2a0d10', 'd': '#521717', 'r': '#8f2a2a', 'R': '#c8323c', 'e': '#ff3a4a',
    'o': '#f08a3c', 'y': '#ffcf4a', 'w': '#e8dccf', 's': '#b8aca4', 'g': '#6e625c', 'c': '#a9b8c4', 'x': '#050102',
}
N = 32


def parse():
    out, key, rows, mir = {}, None, [], False
    def flush():
        if key is None:
            return
        g = [list((r + '.' * N)[: (16 if mir else N)]) for r in rows[:N]]
        while len(g) < N:
            g.append(['.'] * (16 if mir else N))
        if mir:
            g = [r + r[::-1] for r in g]
        for y, r in enumerate(g):
            for ch in r:
                if ch != '.' and ch not in PAL:
                    raise SystemExit(f'{key}: unknown colour {ch!r} on row {y}')
        out[key] = outline(g)
    for line in SRC.read_text().splitlines():
        if line.startswith('# '):
            flush()
            parts = line[2:].split()
            key, rows, mir = parts[0], [], 'mirror' in parts[1:]
        elif key is not None and line.strip():
            rows.append(line.rstrip())
    flush()
    return out


def outline(g):
    add = []
    for y in range(N):
        for x in range(N):
            if g[y][x] != '.':
                continue
            if any(0 <= x + dx < N and 0 <= y + dy < N and g[y + dy][x + dx] not in '.x' for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                add.append((x, y))
    for x, y in add:
        g[y][x] = 'x'
    return [''.join(r) for r in g]


def main():
    art = parse()
    if len(sys.argv) > 1 and sys.argv[1] == 'preview':
        from PIL import Image, ImageDraw
        S, cols = 6, 6
        keys = list(art)
        rows = (len(keys) + cols - 1) // cols
        im = Image.new('RGB', (cols * (N * S + 16), rows * (N * S + 30)), '#1a0508')
        dr = ImageDraw.Draw(im)
        for i, k in enumerate(keys):
            ox, oy = (i % cols) * (N * S + 16) + 8, (i // cols) * (N * S + 30) + 22
            dr.text((ox, oy - 16), k, fill='#e8dccf')
            for y, r in enumerate(art[k]):
                for x, ch in enumerate(r):
                    if ch != '.':
                        dr.rectangle([ox + x * S, oy + y * S, ox + x * S + S - 1, oy + y * S + S - 1], fill=PAL[ch])
        im.save(sys.argv[2] if len(sys.argv) > 2 else '/tmp/boss-preview.png')
        return
    body = ',\n'.join(f"  '{k}': [\n" + ',\n'.join(f"    '{r}'" for r in rows) + ',\n  ]' for k, rows in art.items())
    pal = ', '.join(f"{k}: '{v}'" for k, v in PAL.items())
    OUT.write_text(
        '// Generated by scripts/boss_art.py from data/boss-art/bosses.txt — do not edit by hand.\n'
        '/** Boss figures, 32×32, one row per string; keys are 1/2/3 (first bosses), lina, and the region number of the\n'
        ' *  later bosses (4–20). */\n'
        f'export const BOSS_PAL: Record<string, string> = {{ {pal} }};\n'
        f'export const BOSS_ART: Record<string, string[]> = {{\n{body},\n}};\n'
    )
    print(f'{len(art)} figures → {OUT.relative_to(ROOT)}')


main()
