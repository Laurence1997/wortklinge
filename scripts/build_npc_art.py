#!/usr/bin/env python3
"""NPC figures (2026-11-26): data/monster-art/npcs.txt → src/data/npcArt.ts (16 rows of 16 palette chars, '/'-joined)."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_sprites import render  # noqa: E402
from artlib import text  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def main():
    out = {}
    for line in (ROOT / 'data/monster-art/npcs.txt').read_text(encoding='utf-8').split('\n'):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        key, _, body = line.partition(':')
        family, _, rest = body.strip().partition(' ')
        out[key.strip()] = '/'.join(text(render(family, rest)))
    ts = ['// GENERATED by scripts/build_npc_art.py from data/monster-art/npcs.txt. Do not edit by hand.',
          '/** NPC figures by name or speaker key: 16 rows of 16 palette characters (DRAWN_PAL), joined by "/". */',
          'export const NPC_ART: Record<string, string> = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';', '']
    (ROOT / 'src/data/npcArt.ts').write_text('\n'.join(ts), encoding='utf-8')
    print(f'{len(out)} NPC figures')


if __name__ == '__main__':
    main()
